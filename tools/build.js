// Build for Cloudflare:
//  1. server/src/logic.js  – the game rules taken straight out of index.html, so server and client always agree
//  2. pages/dist/          – the static game files for Cloudflare Pages (index.html, app files, icons, headers)
// Usage: node tools/build.js
const fs=require("fs"),path=require("path");
const root=path.join(__dirname,"..");
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
const part=(a,b)=>html.split(a)[1].split(b)[0];

// 1. server logic
const logic=part("// ===== LOGIC START =====","// ===== LOGIC END =====");
const fair=part('<script id="fair-src">',"</script>");
fs.writeFileSync(path.join(root,"server","src","logic.js"),
`// GENERATED by tools/build.js from index.html – do not edit by hand.
${logic}
${fair}
export {RULES,MAPS,STANDARD,N,DIRS,FAIR_SEEDS,newRound,getMap,tiltLegal,applyTilt,applyBuild,applyNudge,nudgeCheck,buildCheck};
`);

// 2. static site
const dist=path.join(root,"pages","dist");
fs.rmSync(dist,{recursive:true,force:true});
if(fs.existsSync(path.join(root,"OFFLINE"))){
  // Paused: publish only a notice page, no game, no app files.
  fs.mkdirSync(dist,{recursive:true});
  for(const f of fs.readdirSync(path.join(root,"pages","offline")))fs.copyFileSync(path.join(root,"pages","offline",f),path.join(dist,f));
  console.log("OFFLINE: built server/src/logic.js and the pause page in pages/dist");
  process.exit(0);
}
fs.mkdirSync(path.join(dist,"icons"),{recursive:true});
for(const f of ["index.html","manifest.webmanifest","sw.js","robots.txt","sitemap.xml"])fs.copyFileSync(path.join(root,f),path.join(dist,f));
for(const f of fs.readdirSync(path.join(root,"icons")))fs.copyFileSync(path.join(root,"icons",f),path.join(dist,"icons",f));
fs.copyFileSync(path.join(root,"pages","_headers"),path.join(dist,"_headers"));
console.log("built server/src/logic.js and pages/dist");
